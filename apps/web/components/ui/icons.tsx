/**
 * Set de iconos SVG inline. Estilo lucide: 24×24, stroke-based,
 * `currentColor`. Importable nominalmente; el caller controla
 * tamaño con `size` o vía CSS. Nada de dependencias externas — cada
 * icono es un componente puro de unos pocos paths.
 */

interface IconProps extends Omit<SVGProps<SVGSVGElement>, 'children'> {
  size?: number | undefined;
  style?: CSSProperties | undefined;
}

interface IconWrapperProps extends IconProps {
  children: ReactNode;
}

function Icon({ size = 20, children, style, ...rest }: IconWrapperProps) {
  return (
    <svg
      xmlns="http://www.w3.org/2000/svg"
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={1.75}
      strokeLinecap="round"
      strokeLinejoin="round"
      style={{ flexShrink: 0, ...style }}
      aria-hidden="true"
      {...rest}
    >
      {children}
    </svg>
  );
}

